test('every region has its own colour, and the colours are distinguishable', () => {
  const s = loadBrainScope();
  const rgb = (hex) => [(hex >> 16) & 255, (hex >> 8) & 255, hex & 255];
  const entries = REGIONS.map((r) => [r.id, s.regionColor(r.id)]);
  for (const [id, c] of entries) {
    assert.ok(Number.isInteger(c) && c >= 0 && c <= 0xffffff, `${id} has no colour`);
    assert.ok(Object.prototype.hasOwnProperty.call(s.REGION_COLORS, id), `${id} missing from REGION_COLORS`);
  }
  let worst = Infinity, worstPair = '';
  for (let i = 0; i < entries.length; i++) {
    for (let j = i + 1; j < entries.length; j++) {
      const a = rgb(entries[i][1]), b = rgb(entries[j][1]);
      const d = Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]);
      if (d < worst) { worst = d; worstPair = `${entries[i][0]} vs ${entries[j][0]}`; }
    }
  }
  // 28 colours cannot all be far apart; 40 units of RGB distance is about the practical
  // floor for "tell these two apart as an 8px dot". The palette is generated by spreading
  // hues and then maximising this minimum (see REGION_COLORS in geometry.js).
  assert.ok(worst > 40, `colours too close: ${worstPair} (distance ${worst.toFixed(1)})`);
});

test('every discrete structure sits inside the modelled head volume', () => {
  const s = loadBrainScope();
  const lim = { x: s.BRAIN.sx * 1.35, y: s.BRAIN.sy * 1.6, z: s.BRAIN.sz * 1.1 };
  for (const spec of s.SUBCORTICAL_SPECS) {
    for (const part of spec.parts) {
      const pts = part.at ? [part.at] : (part.points || [part.from, part.to]);
      for (const p of pts) {
        assert.ok(Math.abs(p[0]) < lim.x, `${spec.id} x=${p[0]} outside the head`);
        assert.ok(Math.abs(p[1]) < lim.y, `${spec.id} y=${p[1]} outside the head`);
        assert.ok(Math.abs(p[2]) < lim.z, `${spec.id} z=${p[2]} outside the head`);
      }
      if (part.at && spec.mirror) assert.ok(part.at[0] >= 0, `${spec.id} mirrored parts must be authored on the right (+x)`);
    }
  }
});

