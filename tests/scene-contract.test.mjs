test('the default camera is a left-lateral three-quarter, and resetView returns to it', () => {
  const src = read('src/brain/scene.js');
  const pos = (src.match(/BRAIN_HOME_POS = \[([^\]]+)\]/) || [])[1].split(',').map(Number);
  const tgt = (src.match(/BRAIN_HOME_TARGET = \[([^\]]+)\]/) || [])[1].split(',').map(Number);
  assert.equal(pos.length, 3); assert.equal(tgt.length, 3);
  // The left hemisphere is the UNMIRRORED one, and the hemisphere is authored with +x
  // lateral — so the left hemisphere lives at +x and the camera has to be there to see its
  // lateral surface (Broca and Wernicke exist nowhere else). These two facts have to agree.
  assert.ok(/if \(side === 'right'\) mesh\.scale\.x = -1;/.test(read('src/brain/geometry.js')),
    'the RIGHT hemisphere is the mirrored one: +x is the subject\'s left');
  assert.ok(pos[0] > 0, 'the camera must sit on the LEFT hemisphere side (+x)');
  assert.ok(pos[1] > 0, 'the default view looks slightly DOWN at the brain');
  assert.ok(pos[2] > 0, 'the frontal pole must face the camera side, so the pose is a three-quarter not a profile');
  // ~15 degrees above the horizontal: enough to see the superior surface, not a top-down.
  const elev = Math.atan2(pos[1] - tgt[1], Math.hypot(pos[0] - tgt[0], pos[2] - tgt[2])) * 180 / Math.PI;
  assert.ok(elev > 10 && elev < 22, `camera elevation is ${elev.toFixed(1)} degrees`);
  const dist = Math.hypot(pos[0] - tgt[0], pos[1] - tgt[1], pos[2] - tgt[2]);
  assert.ok(dist > 3.0 && dist < 5.0, `home distance ${dist.toFixed(2)} will not frame the whole brain`);
  // Panned off the midline so the brain sits in the gap between the side panel and the Explain
  // card. `tgt[0] < 0` used to stand in for this, but that only held while the pan went screen-LEFT;
  // since round 4 the camera sits further back and the pan goes the other way, to pull the
  // cerebellum out from under the Explain card. Check the pan itself instead of its x component:
  // the offset of the target along the camera's screen-right axis must be positive and non-trivial.
  const fwd = [tgt[0] - pos[0], tgt[1] - pos[1], tgt[2] - pos[2]];
  const rLen = Math.hypot(-fwd[2], fwd[0]);
  const right = [-fwd[2] / rLen, 0, fwd[0] / rLen];
  const pan = tgt[0] * right[0] + tgt[2] * right[2];
  assert.ok(pan > 0.03, `the rig is panned by ${pan.toFixed(3)}: the brain will drift under the Explain card`);
  // resetView must fly to the SAME constants, not to a second hard-coded pose
  const reset = src.slice(src.indexOf('resetView()'), src.indexOf('resetView()') + 400);
  assert.ok(/BRAIN_HOME_POS\[0\]/.test(reset) && /BRAIN_HOME_TARGET\[0\]/.test(reset), 'resetView does not use the home constants');
});

test('the cortex is the primary object: cool, semi-matte, front faces, one blended skin', () => {
  const geo = read('src/brain/geometry.js');
  const body = read('src/body.html');
  const sceneDefault = +(read('src/brain/scene.js').match(/setCortexOpacity\(([0-9.]+)\)/) || [])[1];
  const sliderDefault = +(body.match(/id="cortex-opacity"[^>]*value="([0-9.]+)"/) || [])[1];
  assert.equal(sceneDefault, sliderDefault, 'scene default and the #cortex-opacity slider disagree');
  assert.equal(sceneDefault, 0.63, `a ${sceneDefault} shell is not the agreed default`);
  const mat = geo.slice(geo.indexOf('const cortexMaterial'), geo.indexOf('const hemispheres'));
  const rough = +(mat.match(/roughness:\s*([0-9.]+)/) || [])[1];
  assert.ok(rough >= 0.45 && rough <= 0.65, `cortex roughness ${rough}: too glossy hides the gyri, too matte kills the sheen`);
  // Cool and desaturated. A warm shell reads as beige wax against this dark blue UI, and
  // that is exactly what rounds 1-2 produced.
  const hex = parseInt((mat.match(/color:\s*0x([0-9a-f]{6})/i) || [])[1], 16);
  const r = (hex >> 16) & 255, g = (hex >> 8) & 255, b = hex & 255;
  assert.ok(b > r, `cortex colour #${hex.toString(16)} is warm (r ${r} >= b ${b})`);
  assert.ok(Math.max(r, g, b) - Math.min(r, g, b) < 60, 'the cortex must stay desaturated');
  assert.ok(/side: THREE\.FrontSide/.test(mat), 'the shell must render front faces only');
  assert.ok(/depthWrite: false/.test(mat), 'a translucent shell that writes depth hides the structures behind it');
  assert.ok(/forceSinglePass: true/.test(mat), 'the shell must be a single blended skin');
  assert.ok(!/transmission:\s*[1-9.]/.test(mat), 'no transmission: it costs a second scene render and looks like glass');
});

