test('the cortex surface is a few large folds, not noise', () => {
  const s = loadBrainScope();
  const geo = read('src/brain/geometry.js');
  // The crumpled look has one cause every time: displacement whose wavelength is close to
  // the vertex spacing. These four numbers are the guard rails against re-introducing it.
  assert.ok(s.BRAIN.foldOctaves <= 2, `${s.BRAIN.foldOctaves} octaves puts detail at the vertex spacing`);
  assert.ok(s.BRAIN.foldFreq <= 2.0, `fold frequency ${s.BRAIN.foldFreq} is too high for readable gyri`);
  assert.equal(s.BRAIN.fineAmp, undefined, 'the fine high-frequency octave is back');
  const depthPct = 100 * s.BRAIN.sulcusDepth / s.BRAIN.meanRadius;
  assert.ok(depthPct >= 2.0 && depthPct <= 3.5, `sulcus depth is ${depthPct.toFixed(1)}% of the radius`);
  assert.ok(s.BRAIN.sylvianDepth > s.BRAIN.sulcusDepth && s.BRAIN.centralDepth > s.BRAIN.sulcusDepth,
    'the two named fissures must be deeper than the anonymous folds');
  // domain warp, and the relaxation pass that removes the icosahedron's own faceting
  assert.ok(s.BRAIN.warpAmp > 0 && s.BRAIN.warpFreq < s.BRAIN.foldFreq, 'the fold field is not domain-warped');
  assert.ok(/function brainSmoothPositions/.test(geo), 'no Laplacian smoothing pass');
  assert.ok(s.BRAIN.smoothPasses >= 2, `only ${s.BRAIN.smoothPasses} smoothing pass(es)`);
  assert.equal((geo.match(/^\s+brainSmoothPositions\(geo,/gm) || []).length, 2,
    'both the hemisphere and the cerebellum have to be relaxed');
  // triangle budget: 20*(detail+1)^2 per hemisphere, and the whole scene must fit in 120k
  const hemiTris = 20 * Math.pow(s.BRAIN.detail + 1, 2);
  assert.ok(2 * hemiTris < 100000, `hemispheres alone are ${2 * hemiTris} triangles`);
});

